#!/usr/bin/env python3
"""The 2600 core's save-state blob (docs/SAVESTATE.md), written down once.

  savestate.py gen [--check]
      writes src/fpga/core/a26_ss_pkg.sv (the controller's constants) and the
      generated tables in docs/SAVESTATE.md from this file, the chain map
      (tools/savestate/chain_map.txt, from apply.sh) and the measured chain
      length (tools/savestate/chain_bits.txt, from sim/run_sschain.sh);
      --check only compares and exits 1 when a file is out of date.
  savestate.py verify BLOB [--cart-crc X] [--cart-len N] [--mapper W] [--flags W]
      the checks the core makes on a load (SAVESTATE.md 4), on a file;
      prints what is wrong, exit 0 when nothing is.
  savestate.py show BLOB
      the header and the areas' summaries.
  savestate.py sig
      the chain signature: CRC32 of the chain map's lines (comments left
      out), the hand-chained segments (HAND below) and the length.

The layout follows the Intellivision core's tools/savestate.py (our own,
MIT): a header of 16 big-endian words, then the payload at fixed offsets.
SPDX-License-Identifier: MIT
"""
import argparse
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))

MAGIC = 0x41323653          # "A26S"
VERSION = 1
BLOB_BYTES = 131072
HDR_WORDS = 16
# payload areas, in 32-bit words from the blob's start
W_CHAIN = 16                # the scan chain, first bit out in bit 31 of the first word
W_RIOT = 512                # RIOT RAM, 128 bytes, the first in bits 31-24
W_FA2 = 544                 # FA2 work RAM, 256 bytes
W_AVOX = 608                # AtariVox register file, 256 words
W_GAP = 864                 # unused, 0
W_CRAM = 1024               # cartridge RAM, 32 KiB (the SRAM's cart area, bytes 0-32767)
W_END = 9216                # the live part ends: 36,864 bytes
CRAM_BYTES = 32768
FLAGS_CHECKED = 0x00000001  # flags bits a load checks: PAL

HEADER = [   # (word, name, meaning)
    (0, "magic", '$41323653 "A26S"'),
    (1, "version", "format version (%d)" % VERSION),
    (2, "size", "blob size in bytes (%d)" % BLOB_BYTES),
    (3, "length", "payload bytes from byte 64 (%d)" % ((W_END - HDR_WORDS) * 4)),
    (4, "cart_crc", "the cartridge image's CRC32 (zlib's, over every byte the loader took)"),
    (5, "cart_len", "the image's length in bytes"),
    (6, "mapper", "bits 5-0 the scheme the core runs (run_bs), 8 Superchip, 14-12 detect2600's revision"),
    (7, "flags", "bit 0 PAL (checked), 1 SaveKey on, 2 AtariVox on, 6-4 Port 1 Input, 10-8 Port 2 Input, 16 the Mapper menu forced the scheme (not checked)"),
    (8, "crc", "CRC32 of the payload (bytes 64 .. %d)" % (W_END * 4 - 1)),
    (9, "chain_bits", "the scan chain's length in bits"),
    (10, "chain_sig", "the chain signature (savestate.py sig): a blob of another chain is refused"),
    (11, "cram_bytes", "cartridge RAM bytes in the blob (%d)" % CRAM_BYTES),
    (12, "ar_crc", "the Supercharger BIOS's CRC32 (0: v1 refuses the Supercharger)"),
    (13, "daria", "DARIA's scheme and RAM size (0: v1 refuses the ARM cartridges)"),
    (14, "reserved", "0"),
    (15, "reserved", "0"),
]
H = {name: w for w, name, _ in HEADER if name != "reserved"}

# The segments chained by hand (our own modules), in chain order after the
# generated machine (Atari7800 main): (module, bits, what)
HAND = [
    ("paddle_timer4", 696, "{cc, old_clear, pv}, then per paddle {high_count, lowest, highest, difference, m, read_count, chg, cleared, lgh, pend}"),
    ("virtual_axis5", 245, "slot, per axis {pos16, vel, analog_on, rest, rest_valid}, axes 0-1 phase"),
    ("lightgun", None, "(generated: lightgun.sv)"),
    ("EEPROM_24LC0X", None, "(generated: EEPROM_24LC256.sv, the SaveKey's bus state)"),
    ("atarivox", 235, "div; avox_rx {sync, cnt, bitn, sh, got, got_byte}, {abort_set, ready_set, scp, esc}, {wp, rp, count}; avox_engine's 130 bits and its RAMs' 38 address bits"),
    ("atari2600_pocket", 15, "{ms_div, ms_tick}: the virtual axes' 1 kHz tick"),
]

PKG = os.path.join(ROOT, "src", "fpga", "core", "a26_ss_pkg.sv")
DOC = os.path.join(ROOT, "docs", "SAVESTATE.md")
MAP = os.path.join(HERE, "chain_map.txt")
BITS = os.path.join(HERE, "chain_bits.txt")


def chain_bits():
    try:
        return int(open(BITS).read().split()[0])
    except (OSError, ValueError, IndexError):
        return 0


def chain_sig(n=None):
    n = chain_bits() if n is None else n
    lines = [l.rstrip("\n") for l in open(MAP) if l.strip() and not l.startswith("#")]
    hand = ["%s\t%s\t%s" % (m, b, w) for m, b, w in HAND]
    return zlib.crc32(("\n".join(lines + hand + ["bits %d" % n]) + "\n").encode())


def pkg_text():
    n = chain_bits()
    s = chain_sig(n)
    out = ["// Generated by tools/savestate/savestate.py gen: do not edit.",
           "// The save-state blob's layout (docs/SAVESTATE.md 3).",
           "// SPDX-License-Identifier: MIT",
           "",
           "/* verilator lint_off UNUSEDPARAM */  // the whole layout, some words for later steps",
           "package a26_ss_pkg;",
           "\tlocalparam logic [31:0] SS_MAGIC         = 32'h%08X;   // \"A26S\"" % MAGIC,
           "\tlocalparam logic [31:0] SS_VERSION       = 32'd%d;" % VERSION,
           "\tlocalparam int          SS_BLOB_BYTES    = %d;" % BLOB_BYTES,
           "\tlocalparam int          SS_HDR_WORDS     = %d;" % HDR_WORDS,
           "\tlocalparam int          SS_PAYLOAD       = %d;" % ((W_END - HDR_WORDS) * 4),
           "\tlocalparam int          SS_W_CHAIN       = %d;" % W_CHAIN,
           "\tlocalparam int          SS_W_RIOT        = %d;" % W_RIOT,
           "\tlocalparam int          SS_W_FA2         = %d;" % W_FA2,
           "\tlocalparam int          SS_W_AVOX        = %d;" % W_AVOX,
           "\tlocalparam int          SS_W_GAP         = %d;" % W_GAP,
           "\tlocalparam int          SS_W_CRAM        = %d;" % W_CRAM,
           "\tlocalparam int          SS_W_END         = %d;" % W_END,
           "\tlocalparam int          SS_CRAM_BYTES    = %d;" % CRAM_BYTES,
           "\tlocalparam int          SS_CHAIN_BITS    = %d;" % n,
           "\tlocalparam logic [31:0] SS_CHAIN_SIG     = 32'h%08X;" % s,
           "\tlocalparam logic [31:0] SS_FLAGS_CHECKED = 32'h%08X;" % FLAGS_CHECKED]
    for name, w in H.items():
        out.append("\tlocalparam int          SS_H_%-12s = %d;" % (name.upper(), w))
    out += ["endpackage", "/* verilator lint_on UNUSEDPARAM */", ""]
    return "\n".join(out)


def doc_text():
    n = chain_bits()
    cw = (n + 31) // 32
    t = ["<!-- BEGIN GENERATED by tools/savestate/savestate.py gen: do not edit -->", "",
         "Header (bytes 0-63, 32-bit words, big-endian):", "",
         "| Word | Byte | Field | Value |", "|---|---|---|---|"]
    for w, name, what in HEADER:
        t.append("| %d | %d | %s | %s |" % (w, 4 * w, name, what))
    t += ["", "Payload:", "", "| Bytes | Words | Part |", "|---|---|---|",
          "| %d-%d | %d-%d | the scan chain: %d bits (signature $%08X), %d words, the first bit out in bit 31 of word %d; the last word's bits past the chain 0 |"
          % (4 * W_CHAIN, 4 * (W_CHAIN + cw) - 1, W_CHAIN, W_CHAIN + cw - 1, n, chain_sig(n), cw, W_CHAIN),
          "| %d-%d | %d-%d | 0 |" % (4 * (W_CHAIN + cw), 4 * W_RIOT - 1, W_CHAIN + cw, W_RIOT - 1),
          "| %d-%d | %d-%d | RIOT RAM, 128 bytes, four a word (the first in bits 31-24) |" % (4 * W_RIOT, 4 * W_FA2 - 1, W_RIOT, W_FA2 - 1),
          "| %d-%d | %d-%d | FA2 work RAM, 256 bytes, as the RIOT RAM |" % (4 * W_FA2, 4 * W_AVOX - 1, W_FA2, W_AVOX - 1),
          "| %d-%d | %d-%d | AtariVox register file, 256 words |" % (4 * W_AVOX, 4 * W_GAP - 1, W_AVOX, W_GAP - 1),
          "| %d-%d | %d-%d | 0 |" % (4 * W_GAP, 4 * W_CRAM - 1, W_GAP, W_CRAM - 1),
          "| %d-%d | %d-%d | cartridge RAM: the SRAM's cartridge area, bytes 0-%d, as the RIOT RAM |" % (4 * W_CRAM, 4 * W_END - 1, W_CRAM, W_END - 1, CRAM_BYTES - 1),
          "| %d-%d | | not stored: read as 0, and a load refuses a blob with anything else written there |" % (4 * W_END, BLOB_BYTES - 1),
          "", "The chain's hand-made segments, after the machine's (in chain order):", "",
          "| Module | Bits | Registers |", "|---|---|---|"]
    for m, b, w in HAND:
        t.append("| %s | %s | %s |" % (m, b if b is not None else "", w))
    t += ["", "<!-- END GENERATED -->"]
    return "\n".join(t)


def gen(check):
    bad = 0
    p = pkg_text()
    if not os.path.exists(PKG) or open(PKG).read() != p:
        bad += 1
        if not check:
            open(PKG, "w").write(p)
            print("wrote", PKG)
    if os.path.exists(DOC):
        d = open(DOC).read()
        a = d.find("<!-- BEGIN GENERATED")
        b = d.find("<!-- END GENERATED -->")
        if a >= 0 and b > a:
            new = d[:a] + doc_text() + d[b + len("<!-- END GENERATED -->"):]
            if new != d:
                bad += 1
                if not check:
                    open(DOC, "w").write(new)
                    print("wrote", DOC)
    if check:
        print("savestate.py gen --check:", "out of date" if bad else "up to date")
        return 1 if bad else 0
    return 0


def words(blob):
    return [int.from_bytes(blob[i:i + 4], "big") for i in range(0, len(blob), 4)]


def verify(path, a):
    blob = open(path, "rb").read()
    probs = []
    if len(blob) != BLOB_BYTES:
        probs.append("size %d, not %d" % (len(blob), BLOB_BYTES))
        blob = blob.ljust(BLOB_BYTES, b"\0")[:BLOB_BYTES]
    w = words(blob)
    n = chain_bits()
    exp = {0: MAGIC, 1: VERSION, 2: BLOB_BYTES, 3: (W_END - HDR_WORDS) * 4, 9: n, 10: chain_sig(n), 11: CRAM_BYTES,
           12: 0, 13: 0, 14: 0, 15: 0}
    for k, v in exp.items():
        if w[k] != v:
            probs.append("header word %d (%s) $%08X, expected $%08X" % (k, HEADER[k][1], w[k], v))
    for k, v in (("cart_crc", a.cart_crc), ("cart_len", a.cart_len), ("mapper", a.mapper)):
        if v is not None and w[H[k]] != v:
            probs.append("header %s $%08X, expected $%08X" % (k, w[H[k]], v))
    if a.flags is not None and (w[H["flags"]] ^ a.flags) & FLAGS_CHECKED:
        probs.append("header flags $%08X: PAL differs from $%08X" % (w[H["flags"]], a.flags))
    crc = zlib.crc32(blob[64:W_END * 4])
    if crc != w[H["crc"]]:
        probs.append("payload CRC32 $%08X, header says $%08X" % (crc, w[H["crc"]]))
    cw = (n + 31) // 32
    last_bits = n - 32 * (cw - 1)
    if cw and last_bits < 32 and w[W_CHAIN + cw - 1] & ((1 << (32 - last_bits)) - 1):
        probs.append("the last chain word's padding is not 0")
    if any(w[W_CHAIN + cw:W_RIOT]) or any(w[W_GAP:W_CRAM]):
        probs.append("an unused area is not 0")
    if any(blob[W_END * 4:]):
        probs.append("bytes past the live part are not 0")
    for p in probs:
        print("  " + p)
    print("verify %s: %s" % (path, "ok" if not probs else "%d problems" % len(probs)))
    return 1 if probs else 0


def show(path):
    blob = open(path, "rb").read().ljust(BLOB_BYTES, b"\0")
    w = words(blob)
    for k, name, _ in HEADER:
        print("  %2d %-10s $%08X" % (k, name, w[k]))
    for name, a, b in (("chain", W_CHAIN, W_RIOT), ("riot", W_RIOT, W_FA2), ("fa2", W_FA2, W_AVOX),
                       ("avox", W_AVOX, W_GAP), ("cram", W_CRAM, W_END)):
        seg = blob[4 * a:4 * b]
        print("  %-6s bytes %6d-%6d  crc32 $%08X  nonzero %d" % (name, 4 * a, 4 * b - 1, zlib.crc32(seg), sum(1 for x in seg if x)))


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen")
    g.add_argument("--check", action="store_true")
    v = sub.add_parser("verify")
    v.add_argument("blob")
    v.add_argument("--cart-crc", type=lambda x: int(x, 0))
    v.add_argument("--cart-len", type=lambda x: int(x, 0))
    v.add_argument("--mapper", type=lambda x: int(x, 0))
    v.add_argument("--flags", type=lambda x: int(x, 0))
    s = sub.add_parser("show")
    s.add_argument("blob")
    sub.add_parser("sig")
    a = ap.parse_args()
    if a.cmd == "gen":
        return gen(a.check)
    if a.cmd == "verify":
        return verify(a.blob, a)
    if a.cmd == "show":
        return show(a.blob) or 0
    if a.cmd == "sig":
        print("chain bits %d, signature $%08X" % (chain_bits(), chain_sig()))
        return 0


if __name__ == "__main__":
    sys.exit(main())
