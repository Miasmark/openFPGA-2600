#!/usr/bin/env python3
"""Write a stand-in for atari2600_pocket for sim/tb_core_top.sv.

  make_wrap_stub.py WRAPPER.sv > stub.sv

The stub keeps the wrapper's port list as the wrapper declares it (copied,
`ifdef lines included), so core_top.v connects to it exactly as to the real
module, and replaces the body with what the bench needs:
- every setting input stays readable by the bench (tb.dut.atari.<port>);
- a blanking pattern on HBlank, with video_pal_o following region_setting
  == PAL and tia_mode_o following palette_temp[0], so the bench can see the
  scaler slot core_top.v sends for each, independently of tia_mode;
- counts and the first bytes of each download (cart_download, arfw_download);
- counts, the last address and data of the save slot bridge writes, and
  read data that encodes the address (the bridge read mux);
- every other output tied to 0.
"""
import re
import sys

src = open(sys.argv[1]).read().splitlines()
start = next(i for i, l in enumerate(src) if re.match(r"\s*module\s+atari2600_pocket\b", l))
end = next(i for i in range(start, len(src)) if re.match(r"\s*\);", src[i]))
header = src[start:end + 1]

DRIVEN = {"HBlank", "VBlank", "ce_pix", "video_pal_o", "tia_mode_o", "is_pal_o",
          "sk_bridge_dout", "fa2_bridge_dout"}
tie = []
for l in header:
    s = l.strip()
    if re.match(r"`(ifdef|ifndef|else|elsif|endif)\b", s):
        tie.append(s)
        continue
    m = re.match(r"output\s+(?:wire|reg|logic)?\s*(\[[^\]]+\])?\s*(\w+)", s)
    if m and m.group(2) not in DRIVEN:
        tie.append(f"assign {m.group(2)} = '0;")

body = r"""
// ---- stub body (sim/make_wrap_stub.py) ----
/* verilator lint_off UNUSEDSIGNAL */
reg [7:0] hcnt = 8'd0;
always @(posedge clk_sys) hcnt <= hcnt + 8'd1;
assign HBlank      = hcnt[7:6] == 2'b11;
assign VBlank      = 1'b0;
assign ce_pix      = 1'b1;
assign video_pal_o = region_setting == 2'd2;
assign tia_mode_o  = palette_temp[0];
assign is_pal_o    = 1'b0;     // no PLL retune in this bench

integer cart_n = 0, arfw_n = 0;
reg  [7:0] cart_b [0:7];
reg [24:0] cart_a [0:7];
reg  [7:0] arfw_b [0:7];
reg [24:0] arfw_a [0:7];
always @(posedge clk_sys) begin
	if (ioctl_wr && cart_download) begin
		if (cart_n < 8) begin cart_b[cart_n] <= ioctl_dout; cart_a[cart_n] <= ioctl_addr; end
		cart_n <= cart_n + 1;
	end
	if (ioctl_wr && arfw_download) begin
		if (arfw_n < 8) begin arfw_b[arfw_n] <= ioctl_dout; arfw_a[arfw_n] <= ioctl_addr; end
		arfw_n <= arfw_n + 1;
	end
end

integer sk_wr_n = 0, fa2_wr_n = 0, sk_rd_n = 0, fa2_rd_n = 0;
reg [12:0] sk_wr_addr = 0;
reg [31:0] sk_wr_data = 0;
reg  [5:0] fa2_wr_addr = 0;
reg [31:0] fa2_wr_data = 0;
always @(posedge clk_74a) begin
	if (sk_bridge_wr)  begin sk_wr_n  <= sk_wr_n + 1;  sk_wr_addr  <= sk_bridge_addr;  sk_wr_data  <= sk_bridge_din;  end
	if (fa2_bridge_wr) begin fa2_wr_n <= fa2_wr_n + 1; fa2_wr_addr <= fa2_bridge_addr; fa2_wr_data <= fa2_bridge_din; end
	if (sk_bridge_rd)  sk_rd_n  <= sk_rd_n + 1;
	if (fa2_bridge_rd) fa2_rd_n <= fa2_rd_n + 1;
end
assign sk_bridge_dout  = {16'h5E00, 3'd0, sk_bridge_addr};
assign fa2_bridge_dout = {16'hFA20, 10'd0, fa2_bridge_addr};
/* verilator lint_on UNUSEDSIGNAL */
"""

print("// Generated by sim/make_wrap_stub.py from " + sys.argv[1] + "; do not edit.")
print("`default_nettype none")
print("\n".join(header))
print(body)
print("\n".join(tie))
print("endmodule")
print("`default_nettype wire")
